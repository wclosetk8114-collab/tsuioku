/* その年のいちばん大きな出来事（w が小さいものを優先） */
function topOf(y) {
  const list = HISTORY.filter((e) => e.y === y).sort((a, b) => a.w - b.w);
  return list[0] || null;
}

/* 期間のなかから、重みが maxW 以下の出来事を拾う */
function between(from, to, maxW) {
  const w = maxW || 1;
  return HISTORY.filter((e) => e.y >= from && e.y <= to && e.w <= w)
                .sort((a, b) => a.y - b.y || a.m - b.m || a.w - b.w);
}

/* 一年ぶんを全部（調べもの用） */
function allOf(y) {
  return HISTORY.filter((e) => e.y === y).sort((a, b) => a.m - b.m || a.w - b.w);
}

window.History = { HISTORY, topOf, between, allOf };
