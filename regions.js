/* 地名から地域プロファイルを引く */
function regionFor(place) {
  if (!place) return null;
  const s = String(place);
  for (const r of REGIONS) {
    if (s.includes(r.pref.replace("県", "")) ) return r;
    for (const sub of r.subareas || []) {
      if ((sub.towns || []).some((t) => s.includes(t))) return r;
    }
  }
  return null;
}

/* 地名から、さらに細かい地区を引く（産業構造が違うので） */
function subareaFor(region, place) {
  if (!region || !place) return null;
  const s = String(place);
  return (region.subareas || []).find((sub) => (sub.towns || []).some((t) => s.includes(t))) || null;
}

function eraOfRegion(region, y) {
  if (!region) return null;
  return region.eras.find((e) => y >= e.from && y <= e.to) || null;
}

/* その人の一生を、地域の暮らしで割る */
function lifeStages(region, birthYear, deathYear) {
  if (!region || !birthYear) return [];
  const end = deathYear || new Date().getFullYear();
  const marks = [
    { age: 7,  label: "子どものころ" },
    { age: 20, label: "二十代" },
    { age: 35, label: "三十代" },
    { age: 50, label: "五十代" },
    { age: 65, label: "六十代" },
  ];
  const out = [];
  const seen = new Set();
  for (const m of marks) {
    const y = birthYear + m.age;
    if (y > end) break;
    const e = eraOfRegion(region, y);
    if (!e) continue;
    out.push({ age: m.age, year: y, label: m.label, era: e, repeat: seen.has(e.label) });
    seen.add(e.label);
  }
  if (deathYear) {
    const e = eraOfRegion(region, deathYear);
    if (e) out.push({ age: deathYear - birthYear, year: deathYear, label: "晩年", era: e, repeat: seen.has(e.label) });
  }
  return out;
}

/* 映像の禁止事項——その年、その土地にまだ無かったもの */
function anachronisms(region, year) {
  if (!region || !year) return [];
  return (region.arrivals || [])
    .filter((a) => year < a.local)
    .map((a) => ({ what: a.what, note: a.note, from: a.local }));
}

/* その年、まだ「入りはじめたばかり」のもの（全戸にあると描かない） */
function partial(region, year) {
  if (!region || !year) return [];
  return (region.arrivals || [])
    .filter((a) => year >= a.local && year < a.spread)
    .map((a) => ({ what: a.what, note: a.note }));
}

window.Regions = { REGIONS, regionFor, subareaFor, eraOfRegion, lifeStages, anachronisms, partial };
